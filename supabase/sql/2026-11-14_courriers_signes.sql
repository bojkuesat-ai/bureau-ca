-- =====================================================================
-- Courriers signés (14/11/2026) — Espace CA.
-- Appliqué sur le projet (migration « courriers_signes »).
--
-- Tout membre du CA (pas les coopté·es, pas le propriétaire retiré) peut :
--   - taper un courrier (le navigateur en fait un PDF), ou
--   - joindre un fichier (PDF, Word, PowerPoint, OpenDocument),
-- le signer en retapant son mot de passe, puis l'envoyer par mail à tout le CA.
-- La signature est inscrite au registre (type « courrier ») avec un code de
-- vérification serveur ; la qualité du signataire est lue sur le serveur
-- (fonction CA + « Trésorerie de la Caisse » s'il est trésorier de la Caisse).
-- Onglet coupable dans Admin (ca_meta.onglets_off contient « courriers »).
-- =====================================================================

create or replace function public.courrier_peut()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from ca_membres c
                  where c.id = auth.uid() and c.statut = 'actif'
                    and c.role in ('membre', 'owner') and not coalesce(c.hors_ca, false));
$$;
revoke all on function public.courrier_peut() from anon, public;
grant execute on function public.courrier_peut() to authenticated;

create table if not exists public.ca_courriers (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  objet text not null,
  mode text not null check (mode in ('texte', 'fichier')),
  corps text,
  fichier jsonb,
  signataire_id uuid not null,
  signataire_nom text,
  signataire_qualite text,
  empreinte text,
  code text,
  signe_le timestamptz not null default now(),
  pdf_path text,
  envoi jsonb,
  envoye_le timestamptz
);
alter table public.ca_courriers enable row level security;
revoke all on public.ca_courriers from anon, authenticated, public;
grant select on public.ca_courriers to authenticated;
drop policy if exists ca_courriers_sel on public.ca_courriers;
create policy ca_courriers_sel on public.ca_courriers for select to authenticated using (public.courrier_peut());

-- Signer (et créer) un courrier. Mot de passe retapé depuis moins de 2 minutes.
create or replace function public.courrier_signer(p_objet text, p_mode text, p_corps text, p_fichier jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_id uuid := gen_random_uuid(); v_fn text; v_nom text; v_q text; v_emp text; v_code text; c ca_courriers;
begin
  if not courrier_peut() then raise exception 'Réservé aux membres du CA.'; end if;
  if exists (select 1 from ca_meta where id = 1 and coalesce(onglets_off, '[]'::jsonb) ? 'courriers') then
    raise exception 'Les courriers signés sont désactivés (Admin).'; end if;
  if not mfa_ok() then raise exception 'Tapez d''abord le code de double authentification.'; end if;
  perform pvs_mdp_frais();
  if coalesce(trim(p_objet), '') = '' then raise exception 'Objet obligatoire.'; end if;
  if length(trim(p_objet)) > 200 then raise exception 'Objet trop long (200 caractères au plus).'; end if;
  if p_mode = 'texte' then
    if coalesce(trim(p_corps), '') = '' then raise exception 'Le texte du courrier est vide.'; end if;
    if length(p_corps) > 30000 then raise exception 'Texte trop long (30 000 caractères au plus).'; end if;
    p_fichier := null;
  elsif p_mode = 'fichier' then
    p_corps := null;
    if p_fichier is null or coalesce(p_fichier->>'path', '') !~ '^courrier-[A-Za-z0-9._-]+$' then raise exception 'Fichier manquant.'; end if;
    if coalesce(p_fichier->>'hash', '') !~ '^[0-9a-f]{64}$' then raise exception 'Empreinte du fichier invalide.'; end if;
    if lower(coalesce(p_fichier->>'name', '')) !~ '\.(pdf|docx?|pptx?|odt|odp)$' then
      raise exception 'Formats acceptés : PDF, Word, PowerPoint, OpenDocument.'; end if;
    if not exists (select 1 from storage.objects o where o.bucket_id = 'ca-documents'
                    and o.name = p_fichier->>'path' and o.owner = auth.uid()) then
      raise exception 'Fichier introuvable : envoyez-le d''abord.'; end if;
    p_fichier := jsonb_build_object('path', p_fichier->>'path', 'name', left(p_fichier->>'name', 200),
      'hash', p_fichier->>'hash', 'type', left(coalesce(p_fichier->>'type', ''), 120),
      'size', coalesce((p_fichier->>'size')::bigint, 0));
  else
    raise exception 'Choix inconnu.';
  end if;

  select fonction, nullif(trim(coalesce(prenom, '') || ' ' || coalesce(nom, '')), '') into v_fn, v_nom
    from ca_membres where id = auth.uid();
  v_q := coalesce(nullif(trim(v_fn), ''), 'Membre du CA');
  if ca_est_tresorier() and v_q !~* 'tr[ée]sor' then v_q := v_q || ' — Trésorerie de la Caisse'; end if;

  insert into ca_courriers (id, objet, mode, corps, fichier, signataire_id, signataire_nom, signataire_qualite)
  values (v_id, trim(p_objet), p_mode, p_corps, p_fichier, auth.uid(), v_nom, v_q)
  returning * into c;
  v_emp := signature_empreinte(jsonb_build_object('id', c.id, 'numero', c.numero, 'objet', c.objet, 'mode', c.mode,
    'corps', c.corps, 'fichier', c.fichier->>'hash', 'qualite', c.signataire_qualite)::text);
  v_code := signature_interne('ca', 'courrier', c.id::text,
    'Courrier n° ' || c.numero || ' « ' || c.objet || ' » — ' || coalesce(v_nom, '') || ' (' || v_q || ')', v_emp,
    jsonb_build_object('numero', c.numero, 'objet', c.objet, 'qualite', v_q, 'mode', c.mode,
      'fichier', c.fichier->>'name', 'fichier_hash', c.fichier->>'hash'));
  update ca_courriers set empreinte = v_emp, code = v_code, signe_le = (select signe_le from signatures_registre where code = v_code)
   where id = c.id returning * into c;
  return to_jsonb(c);
end $$;
revoke all on function public.courrier_signer(text, text, text, jsonb) from anon, public;
grant execute on function public.courrier_signer(text, text, text, jsonb) to authenticated;

-- Après signature : chemin du PDF signé, puis résultat de l'envoi (signataire uniquement).
create or replace function public.courrier_finaliser(p_id uuid, p_pdf_path text, p_envoi jsonb)
returns jsonb language plpgsql security definer set search_path = public as $$
declare c ca_courriers;
begin
  select * into c from ca_courriers where id = p_id for update;
  if not found then raise exception 'Courrier introuvable.'; end if;
  if c.signataire_id <> auth.uid() or not courrier_peut() then raise exception 'Seul le signataire peut terminer ce courrier.'; end if;
  if coalesce(p_pdf_path, '') <> '' and p_pdf_path is distinct from c.pdf_path then
    if c.pdf_path is not null then raise exception 'Le PDF signé est déjà enregistré.'; end if;
    if p_pdf_path !~ '^courrier-signe-[A-Za-z0-9._-]+\.pdf$' then raise exception 'Chemin du PDF invalide.'; end if;
    if not exists (select 1 from storage.objects o where o.bucket_id = 'ca-documents' and o.name = p_pdf_path and o.owner = auth.uid()) then
      raise exception 'PDF signé introuvable.'; end if;
    update ca_courriers set pdf_path = p_pdf_path where id = p_id;
  end if;
  if p_envoi is not null then
    update ca_courriers set envoi = jsonb_build_object('ok', coalesce((p_envoi->>'ok')::int, 0), 'err', coalesce((p_envoi->>'err')::int, 0),
      'total', coalesce((p_envoi->>'total')::int, 0), 'sans_piece', coalesce((p_envoi->>'sans_piece')::boolean, false)), envoye_le = now()
     where id = p_id;
  end if;
  return (select to_jsonb(x) from ca_courriers x where id = p_id);
end $$;
revoke all on function public.courrier_finaliser(uuid, text, jsonb) from anon, public;
grant execute on function public.courrier_finaliser(uuid, text, jsonb) to authenticated;
