create table if not exists public.fin_mandat (
  id int primary key default 1 check (id = 1),
  statut text not null default 'programme' check (statut in ('programme', 'annule', 'termine')),
  prevenance_le timestamptz not null,
  archives_le timestamptz not null,
  suppression_le timestamptz not null,
  prevenance_fait timestamptz,
  archives jsonb not null default '{}'::jsonb,       -- {ca:{parts:[…],prochain,fini}, compta:{…}}
  destinataires jsonb,                              -- figés le jour des archives
  archives_envoye timestamptz,
  sauvegarde jsonb,                                 -- {chemin, octets, le}
  suppression_fait timestamptz,
  rapport jsonb,
  en_cours timestamptz,
  derniere_erreur text,
  maj_le timestamptz not null default now()
);
alter table public.fin_mandat enable row level security;
revoke all on public.fin_mandat from anon, authenticated, public;
insert into public.fin_mandat (id, prevenance_le, archives_le, suppression_le)
values (1, timestamptz '2027-06-01 10:00:00+02', timestamptz '2027-06-24 10:00:00+02', timestamptz '2027-07-01 00:00:00+02')
on conflict (id) do nothing;

create table if not exists public.fin_mandat_envois (
  id bigint generated by default as identity primary key,
  le timestamptz not null default now(),
  quoi text not null, a text, detail text);
alter table public.fin_mandat_envois enable row level security;
