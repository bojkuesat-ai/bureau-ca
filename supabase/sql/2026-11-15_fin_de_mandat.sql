-- 01/06 : prévenance de tous les comptes (CA, coopté·es, Caisse), sauf le propriétaire.
create or replace function public.fin_mandat_prevenir()
returns integer language plpgsql security definer set search_path = public as $$
declare f fin_mandat; d record; n int := 0; v_p uuid := fm_proprio_id();
  v_sup text; v_arc text;
begin
  select * into f from fin_mandat where id = 1 for update;
  if f.statut <> 'programme' or f.prevenance_fait is not null then return 0; end if;
  v_sup := to_char(f.suppression_le at time zone 'Europe/Brussels', 'DD/MM/YYYY à HH24 "h" MI');
  v_arc := to_char(f.archives_le at time zone 'Europe/Brussels', 'DD/MM/YYYY');
  for d in
    select distinct lower(trim(e)) email from (
      select email e from ca_membres where id is distinct from v_p and statut in ('actif', 'attente')
      union all select email from profiles where id is distinct from v_p and coalesce(approved, false)) x
     where coalesce(trim(e), '') <> ''
  loop
    perform fm_mail(d.email, '📅 Fin de mandat : vos comptes seront supprimés le ' || to_char(f.suppression_le at time zone 'Europe/Brussels', 'DD/MM/YYYY'),
      '<h2 style="margin:0 0 10px">📅 Fin de mandat</h2><p>Bonjour,</p>'
      || '<p>Le mandat du CA se termine. Le <b>' || v_sup || '</b>, <b>tous les comptes</b> de l''Espace CA et de la Caisse seront supprimés, '
      || 'avec toutes les données (messages, documents, demandes, réglages…). Le nouveau CA repartira d''une application vide.</p>'
      || '<div style="background:#fff4e0;border:1px solid #e8b04b;border-radius:10px;padding:12px 14px;margin:12px 0"><b>À faire avant le ' || v_arc || ' :</b><ul style="margin:6px 0 0;padding-left:20px">'
      || '<li>introduire et régler vos <b>demandes de remboursement</b> et vos justificatifs dans la Caisse ;</li>'
      || '<li>télécharger ce que vous voulez garder pour vous.</li></ul></div>'
      || '<p>Le ' || v_arc || ', les <b>archives du CA</b> (PV, documents, votes, budgets…) et la <b>comptabilité de la Caisse</b> seront remises '
      || 'à la présidente, à la secrétaire et au trésorier.</p><p>Merci pour votre engagement !</p>',
      'Bureau étudiant');
    n := n + 1;
  end loop;
  update fin_mandat set prevenance_fait = now(), maj_le = now() where id = 1;
  insert into fin_mandat_envois (quoi, a, detail) values ('prévenance', n || ' adresse(s)', null);
  return n;
end $$;
revoke all on function public.fin_mandat_prevenir() from public, anon, authenticated;

-- Tâche toutes les 10 min : n'appelle la fonction Edge que lorsqu'une étape est due.
create or replace function public.fin_mandat_tick()
returns text language plpgsql security definer set search_path to 'public', 'net' as $$
declare f fin_mandat; v_anon text := 'sb_publishable_xoVRiE99YOepw-sb5Tmtcg_SJ3VE_0s';
begin
  select * into f from fin_mandat where id = 1;
  if not found or f.statut <> 'programme' then return 'rien'; end if;
  if now() >= f.prevenance_le and f.prevenance_fait is null and now() < f.archives_le then
    perform fin_mandat_prevenir(); return 'prévenance';
  end if;
  if (now() >= f.archives_le and f.archives_envoye is null) or (now() >= f.suppression_le and f.suppression_fait is null) then
    if f.en_cours is not null and f.en_cours > now() - interval '9 minutes' then return 'en cours'; end if;
    perform net.http_post(
      url := 'https://mlgzdfyqjhvyubrywuim.supabase.co/functions/v1/fin-mandat',
      headers := jsonb_build_object('Content-Type', 'application/json', 'Authorization', 'Bearer ' || v_anon, 'apikey', v_anon,
                   'x-cron-secret', (select cron_secret from public.bil_config where id = 1)),
      body := jsonb_build_object('action', 'tick'), timeout_milliseconds := 10000);
    return 'étape';
  end if;
  return 'rien';
end $$;
revoke all on function public.fin_mandat_tick() from public, anon, authenticated;

-- Propriétaire : lire l'état, annuler / reprendre, décaler les dates.
create or replace function public.fin_mandat_etat()
returns jsonb language plpgsql stable security definer set search_path = public as $$
begin
  perform proprio_exiger();
  return (select to_jsonb(f) - 'en_cours' from fin_mandat f where id = 1)
    || jsonb_build_object('envois', coalesce((select jsonb_agg(to_jsonb(e) order by e.le desc) from (select * from fin_mandat_envois order by le desc limit 50) e), '[]'::jsonb),
