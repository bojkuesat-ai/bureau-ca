-- Le bilan double authentification du 19/11 part avec l'expéditeur Licence-BE (passe le filtre « propriétaire retiré »).
create or replace function public.mfa_rapport_proprio()
returns integer language plpgsql security definer set search_path = public as $$
declare v_ok text; v_non text; n_ok int; n_non int; d record; n int := 0;
begin
  select count(*) filter (where a_mfa(c.id)), count(*) filter (where not a_mfa(c.id)),
         coalesce(string_agg('<li>' || ca_html(coalesce(nullif(trim(coalesce(prenom,'') || ' ' || coalesce(nom,'')), ''), email)) || coalesce(' — ' || ca_html(nullif(fonction, '')), '') || '</li>', '' order by prenom, nom) filter (where a_mfa(c.id)), ''),
         coalesce(string_agg('<li>' || ca_html(coalesce(nullif(trim(coalesce(prenom,'') || ' ' || coalesce(nom,'')), ''), email)) || coalesce(' — ' || ca_html(nullif(fonction, '')), '') || '</li>', '' order by prenom, nom) filter (where not a_mfa(c.id)), '')
    into n_ok, n_non, v_ok, v_non
    from ca_membres c where mfa_concerne(c.id);
  for d in select distinct email from ca_membres where role in ('owner', 'proprietaire') and statut = 'actif' and coalesce(email, '') <> '' loop
    perform fm_mail(d.email, '🔐 Double authentification : ' || n_ok || '/' || (n_ok + n_non) || ' membres l''ont activée',
      '<h2 style="margin:0 0 10px">Bilan de la double authentification</h2>'
      || '<p>Situation au ' || to_char(now() at time zone 'Europe/Brussels', 'DD/MM/YYYY à HH24:MI') || ' (obligatoire depuis jeudi 00 h).</p>'
      || '<h3 style="margin:16px 0 4px">✅ Activée (' || n_ok || ')</h3><ul>' || v_ok || '</ul>'
      || '<h3 style="margin:16px 0 4px">⏳ Pas encore activée (' || n_non || ')</h3>'
      || case when n_non = 0 then '<p>Personne : tout le CA l''a activée.</p>' else '<ul>' || v_non || '</ul><p>À leur prochaine connexion, l''écran d''activation s''affichera. Vous pouvez les relancer dans Admin › Double authentification.</p>' end,
      'Licence-BE');
    n := n + 1;
  end loop;
  begin perform cron.unschedule('mfa_rapport_1911'); exception when others then null; end;
  return n;
end $$;
revoke all on function public.mfa_rapport_proprio() from public, anon, authenticated;
