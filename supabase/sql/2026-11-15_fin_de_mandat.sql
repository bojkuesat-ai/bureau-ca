create or replace function public.fin_mandat_regler(p_statut text, p_prevenance timestamptz, p_archives timestamptz, p_suppression timestamptz)
returns jsonb language plpgsql security definer set search_path = public as $$
declare f fin_mandat;
begin
  perform proprio_exiger();
  select * into f from fin_mandat where id = 1 for update;
  if f.statut = 'termine' then raise exception 'La fin de mandat est déjà faite.'; end if;
  if p_statut not in ('programme', 'annule') then raise exception 'Choix inconnu.'; end if;
  if not (p_prevenance < p_archives and p_archives < p_suppression) then
    raise exception 'Les dates doivent se suivre : prévenance, puis archives, puis suppression.'; end if;
  if p_suppression - p_archives < interval '24 hours' then raise exception 'Laissez au moins 24 h entre les archives et la suppression.'; end if;
  if p_statut = 'programme' and p_suppression < now() + interval '24 hours' and f.suppression_le is distinct from p_suppression then
    raise exception 'La suppression doit être programmée au moins 24 h à l''avance.'; end if;
  update fin_mandat set statut = p_statut, prevenance_le = p_prevenance, archives_le = p_archives, suppression_le = p_suppression,
    -- archives déjà faites mais nouvelle date future : on les refera à la nouvelle date
    archives = case when p_archives > now() and f.archives_envoye is not null then '{}'::jsonb else archives end,
    archives_envoye = case when p_archives > now() then null else archives_envoye end,
    destinataires = case when p_archives > now() then null else destinataires end,
    prevenance_fait = case when p_prevenance > now() then null else prevenance_fait end,
    sauvegarde = case when p_suppression > now() then null else sauvegarde end,
    derniere_erreur = null, maj_le = now()
   where id = 1;
  insert into fin_mandat_envois (quoi, a, detail) values ('réglage', null,
    p_statut || ' — prévenance ' || to_char(p_prevenance at time zone 'Europe/Brussels', 'DD/MM/YYYY HH24:MI')
    || ', archives ' || to_char(p_archives at time zone 'Europe/Brussels', 'DD/MM/YYYY HH24:MI')
    || ', suppression ' || to_char(p_suppression at time zone 'Europe/Brussels', 'DD/MM/YYYY HH24:MI'));
  return fin_mandat_etat();
end $$;
revoke all on function public.fin_mandat_regler(text, timestamptz, timestamptz, timestamptz) from public, anon;
grant execute on function public.fin_mandat_regler(text, timestamptz, timestamptz, timestamptz) to authenticated;

-- Destinataires des archives (figés par la fonction Edge le jour J).
create or replace function public.fin_mandat_destinataires()
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(x), '[]'::jsonb) from (
    select 'presidente' role, 'Présidence' libelle, trim(coalesce(prenom,'') || ' ' || coalesce(nom,'')) nom, email from (
      select * from ca_membres where statut = 'actif' and role <> 'coopte' and coalesce(email,'') <> ''
         and fonction ~* '^\s*pr[ée]sident' order by created_at limit 1) a
    union all
    select 'secretaire', 'Secrétariat', trim(coalesce(prenom,'') || ' ' || coalesce(nom,'')), email from (
      select * from ca_membres where statut = 'actif' and role <> 'coopte' and coalesce(email,'') <> ''
         and fonction ~* '^\s*secr[ée]taire' order by created_at limit 1) b
    union all
    select 'tresorier', 'Trésorerie', coalesce(nullif(trim(coalesce(c.prenom,'') || ' ' || coalesce(c.nom,'')), ''), p.name), coalesce(nullif(p.email, ''), c.email) from (
      select * from profiles where role = 'tresorier' and coalesce(approved, false) order by created_at limit 1) p
      left join ca_membres c on c.id = p.id
  ) x where coalesce(x.email, '') <> '';
$$;
revoke all on function public.fin_mandat_destinataires() from public, anon, authenticated;

-- 01/07 : tout vider (appelée UNIQUEMENT par la fonction Edge, clé de service).
create or replace function public.fin_mandat_vider()
returns jsonb language plpgsql security definer set search_path = public as $$
declare f fin_mandat; v_p uuid; v_liste text[]; t text; n_users int := 0; n_tables int := 0;
begin
  if coalesce(auth.role(), '') <> 'service_role' then raise exception 'Réservé au serveur.'; end if;
  select * into f from fin_mandat where id = 1 for update;
  if f.statut <> 'programme' then raise exception 'Fin de mandat non programmée.'; end if;
  if now() < f.suppression_le then raise exception 'Trop tôt.'; end if;
  if f.archives_envoye is null then raise exception 'Archives non envoyées : suppression refusée.'; end if;
  if f.sauvegarde is null then raise exception 'Sauvegarde finale absente : suppression refusée.'; end if;
  v_p := fm_proprio_id();
  if v_p is null then raise exception 'Propriétaire introuvable : suppression refusée.'; end if;

  select array_agg(c.relname::text order by c.relname) into v_liste
    from pg_class c
   where c.relnamespace = 'public'::regnamespace and c.relkind in ('r', 'p')
     and c.relname not in (select nom from fin_mandat_garder)
     and c.relname not in ('ca_membres', 'profiles');
  n_tables := coalesce(array_length(v_liste, 1), 0);

  foreach t in array coalesce(v_liste, '{}') || array['ca_membres', 'profiles'] loop
    execute format('alter table public.%I disable trigger user', t);
  end loop;
  if n_tables > 0 then
    execute 'truncate table ' || (select string_agg(format('public.%I', x), ', ') from unnest(v_liste) x) || ' restart identity cascade';
  end if;
  delete from auth.users where id <> v_p;
  get diagnostics n_users = row_count;
  delete from ca_membres where id <> v_p;
  delete from profiles where id <> v_p;
  foreach t in array coalesce(v_liste, '{}') || array['ca_membres', 'profiles'] loop
    execute format('alter table public.%I enable trigger user', t);
  end loop;

  -- Réglages liés aux personnes : remis à zéro.
  update ca_meta set secretaires = '[]'::jsonb, direction = '[]'::jsonb, salle_resp = '{}', code_coopte = null,
    bilan_actif = false, bilan_etat = 'ferme', bilan_publie = null, bilan_publie_le = null, bilan_relance_le = null where id = 1;
  update caisse_config set treso_email = null, commission_membres = '{}', updated_at = now() where id = 1;
  update proprio_config set gj_cosignataire = null, maj_le = now() where id = 1;
  -- Nouveau secret : plus aucun ancien code de signature n'est valable.
  update signatures_secret set secret = encode(extensions.gen_random_bytes(32), 'hex'), cree_le = now() where id = 1;

  update fin_mandat set suppression_fait = now(), statut = 'termine',
    rapport = jsonb_build_object('comptes_supprimes', n_users, 'tables_videes', n_tables), maj_le = now() where id = 1;
  return jsonb_build_object('comptes_supprimes', n_users, 'tables_videes', n_tables, 'tables', to_jsonb(v_liste));
end $$;
revoke all on function public.fin_mandat_vider() from public, anon, authenticated;
grant execute on function public.fin_mandat_vider() to service_role;

