-- Le propriétaire (owner tant qu'il est au CA, proprietaire après la passation).
create or replace function public.fm_proprio_id()
returns uuid language sql stable security definer set search_path = public as $$
  select id from ca_membres where role in ('owner', 'proprietaire') order by (role = 'owner') desc, created_at limit 1;
